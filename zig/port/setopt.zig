            if (Curl_setopt_get_ptr_ref(data, PTR_REF_STATE_REFERER)) |oldref| {
                Curl_bufref_free(oldref);
            }
        },
        CURLOPT_USERAGENT => return Curl_setstropt(data, STRING_USERAGENT, ptr),
        CURLOPT_COOKIE => return Curl_setstropt(data, STRING_COOKIE, ptr),
        CURLOPT_COOKIEFILE => return cookiefile(data, ptr),
        CURLOPT_COOKIEJAR => {
