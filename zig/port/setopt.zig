        CURLOPT_PROXY_TLSAUTH_PASSWORD,
        CURLOPT_PROXY_TLSAUTH_TYPE,
        => return CURLE_NOT_BUILT_IN,
        CURLOPT_HSTSREADDATA => {
            if (!enable_hsts) return CURLE_UNKNOWN_OPTION;
            setoptSetPtr(data, PTR_SET_HSTS_READ_USERP, ptr);
        },
        CURLOPT_HSTSWRITEDATA => {
            if (!enable_hsts) return CURLE_UNKNOWN_OPTION;
            setoptSetPtr(data, PTR_SET_HSTS_WRITE_USERP, ptr);
        },
        CURLOPT_HSTS => {
            if (!enable_hsts) return CURLE_UNKNOWN_OPTION;
            if (Curl_setopt_get_ptr(data, PTR_DATA_HSTS) == null) {
                const hsts = Curl_hsts_init() orelse return CURLE_OUT_OF_MEMORY;
                Curl_setopt_set_ptr(data, PTR_DATA_HSTS, hsts);
            }
            if (ptr) |p| {
                result = Curl_setstropt(data, STRING_HSTS, p);
                if (result != CURLE_OK) return result;
                appendHstslist(data, p) catch return CURLE_OUT_OF_MEMORY;
            } else {
                if (setoptGetPtr(curl_slist, data, PTR_STATE_HSTSLIST)) |old_h| {
                    curl_slist_free_all(old_h);
                    Curl_setopt_set_ptr(data, PTR_STATE_HSTSLIST, null);
                }
                if (Curl_setopt_get_ptr(data, PTR_DATA_SHARE) == null or Curl_setopt_get_ptr(data, PTR_SHARE_HSTS) == null) {
                    if (setoptGetPtrRef(?*anyopaque, data, PTR_REF_DATA_HSTS)) |hsts_ref| {
                        Curl_hsts_cleanup(hsts_ref);
                    }
                }
            }
        },
        CURLOPT_ALTSVC => {
            if (Curl_setopt_get_ptr(data, PTR_DATA_ASI) == null) {
                const asi = Curl_altsvc_init() orelse return CURLE_OUT_OF_MEMORY;
                Curl_setopt_set_ptr(data, PTR_DATA_ASI, asi);
            }
            result = Curl_setstropt(data, STRING_ALTSVC, ptr);
            if (result != CURLE_OK) return result;
            if (ptr) |p| {
                return Curl_altsvc_load(Curl_setopt_get_ptr(data, PTR_DATA_ASI), p);
            }
        },
        CURLOPT_ECH => return setoptEch(data, ptr),
        else => return CURLE_UNKNOWN_OPTION,
    }
    return result;
}

fn setoptCptr(data: *Curl_easy, option: CURLoption, ptr: ?[*:0]const u8) CURLcode {
    const handlers = [_]*const fn (*Curl_easy, CURLoption, ?[*:0]const u8) CURLcode{
        setoptCptrMisc,
        setoptCptrSsl,
        setoptCptrProxy,
        setoptCptrNet,
        setoptCptrFtp,
        setoptCptrHttpMqtt,
    };
    for (handlers) |handler| {
        const result = handler(data, option, ptr);
        if (result != CURLE_UNKNOWN_OPTION) return result;
    }
    return CURLE_UNKNOWN_OPTION;
}

