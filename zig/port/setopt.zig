fn setoptOfft(data: *Curl_easy, option: CURLoption, offt: curl_off_t) CURLcode {
    switch (option) {
        CURLOPT_TIMEVALUE_LARGE => Curl_setopt_set_i64(data, FIELD_TIMEVALUE, offt),
        CURLOPT_POSTFIELDSIZE_LARGE => {
            if (offt < -1) return CURLE_BAD_FUNCTION_ARGUMENT;
            const cur_size = Curl_setopt_get_i64(data, FIELD_POSTFIELDSIZE);
            if (cur_size < offt) {
                if (Curl_setopt_get_ptr(data, PTR_SET_STR_COPYPOSTFIELDS)) |old_copy| {
                    mem.free(old_copy);
                    Curl_setopt_set_ptr(data, PTR_SET_STR_COPYPOSTFIELDS, null);
                    Curl_setopt_set_ptr(data, PTR_SET_POSTFIELDS, null);
                }
            }
            Curl_setopt_set_i64(data, FIELD_POSTFIELDSIZE, offt);
        },
        CURLOPT_INFILESIZE_LARGE => {
            if (offt < -1) return CURLE_BAD_FUNCTION_ARGUMENT;
            Curl_setopt_set_i64(data, FIELD_FILESIZE, offt);
        },
        CURLOPT_MAX_SEND_SPEED_LARGE => {
            if (offt < 0) return CURLE_BAD_FUNCTION_ARGUMENT;
            Curl_setopt_set_i64(data, FIELD_MAX_SEND_SPEED, offt);
            if (setoptGetPtrRef(headers_sock.CurlRlimit, data, PTR_REF_PROGRESS_UL_RLIMIT)) |rlimit_ptr| {
                const now = Curl_pgrs_now(data);
                headers_sock.Curl_rlimit_init(
                    rlimit_ptr,
                    offt,
                    @max(offt, 32 * 1024),
                    now,
                );
            }
        },
        CURLOPT_MAX_RECV_SPEED_LARGE => {
            if (offt < 0) return CURLE_BAD_FUNCTION_ARGUMENT;
            Curl_setopt_set_i64(data, FIELD_MAX_RECV_SPEED, offt);
            if (setoptGetPtrRef(headers_sock.CurlRlimit, data, PTR_REF_PROGRESS_DL_RLIMIT)) |rlimit_ptr| {
                const now = Curl_pgrs_now(data);
                headers_sock.Curl_rlimit_init(
                    rlimit_ptr,
                    offt,
                    @max(offt, 32 * 1024),
                    now,
                );
            }
        },
        CURLOPT_RESUME_FROM_LARGE => {
            if (offt < -1) return CURLE_BAD_FUNCTION_ARGUMENT;
            Curl_setopt_set_i64(data, FIELD_SET_RESUME_FROM, offt);
        },
        CURLOPT_MAXFILESIZE_LARGE => {
            if (offt < 0) return CURLE_BAD_FUNCTION_ARGUMENT;
            Curl_setopt_set_i64(data, FIELD_MAX_FILESIZE, offt);
        },
        else => return CURLE_UNKNOWN_OPTION,
    }
    return CURLE_OK;
}

fn setoptBlob(data: *Curl_easy, option: CURLoption, blob: ?*const curl_blob) CURLcode {
    switch (option) {
        CURLOPT_SSLCERT_BLOB => return Curl_setblobopt(Curl_easy_blob_ptr(data, BLOB_CERT), blob),
        CURLOPT_PROXY_SSLCERT_BLOB => return Curl_setblobopt(Curl_easy_blob_ptr(data, BLOB_CERT_PROXY), blob),
        CURLOPT_PROXY_SSLKEY_BLOB => return Curl_setblobopt(Curl_easy_blob_ptr(data, BLOB_KEY_PROXY), blob),
        CURLOPT_PROXY_CAINFO_BLOB => {
            if (use_ssl and sslSupports(data, SSLSUPP_CAINFO_BLOB)) {
                const result = Curl_setblobopt(Curl_easy_blob_ptr(data, BLOB_CAINFO_PROXY), blob);
                if (result == CURLE_OK) {
                    Curl_setopt_set_bit(data, BIT_PROXY_SSL_CUSTOM_CABLOB, true);
                }
                return result;
            }
            return CURLE_NOT_BUILT_IN;
        },
        CURLOPT_PROXY_ISSUERCERT_BLOB => {
            if (sslSupports(data, SSLSUPP_ISSUERCERT_BLOB)) {
                return Curl_setblobopt(Curl_easy_blob_ptr(data, BLOB_SSL_ISSUERCERT_PROXY), blob);
            }
            return CURLE_NOT_BUILT_IN;
        },
        CURLOPT_SSLKEY_BLOB => return Curl_setblobopt(Curl_easy_blob_ptr(data, BLOB_KEY), blob),
        CURLOPT_CAINFO_BLOB => {
            if (use_ssl and sslSupports(data, SSLSUPP_CAINFO_BLOB)) {
                const result = Curl_setblobopt(Curl_easy_blob_ptr(data, BLOB_CAINFO), blob);
                if (result == CURLE_OK) {
                    Curl_setopt_set_bit(data, BIT_SSL_CUSTOM_CABLOB, true);
                }
                return result;
            }
            return CURLE_NOT_BUILT_IN;
        },
        CURLOPT_ISSUERCERT_BLOB => {
            if (sslSupports(data, SSLSUPP_ISSUERCERT_BLOB)) {
                return Curl_setblobopt(Curl_easy_blob_ptr(data, BLOB_SSL_ISSUERCERT), blob);
            }
            return CURLE_NOT_BUILT_IN;
        },
        else => return CURLE_UNKNOWN_OPTION,
    }
}

pub export fn Curl_vsetopt_zig(
    data: *Curl_easy,
    option: CURLoption,
    larg: c_long,
    parg: ?*anyopaque,
    oarg: curl_off_t,
) callconv(.c) CURLcode {
    if (option < CURLOPTTYPE_OBJECTPOINT) {
        return setoptLong(data, option, larg);
    } else if (option < CURLOPTTYPE_FUNCTIONPOINT) {
        switch (option) {
            CURLOPT_HTTPHEADER,
            CURLOPT_QUOTE,
            CURLOPT_POSTQUOTE,
            CURLOPT_TELNETOPTIONS,
            CURLOPT_PREQUOTE,
            CURLOPT_HTTP200ALIASES,
            CURLOPT_MAIL_RCPT,
            CURLOPT_RESOLVE,
            CURLOPT_PROXYHEADER,
            CURLOPT_CONNECT_TO,
            => return setoptSlist(data, option, castOptPtr(curl_slist, parg)),
            CURLOPT_HTTPPOST,
            CURLOPT_MIMEPOST,
            CURLOPT_STDERR,
            CURLOPT_SHARE,
            CURLOPT_CURLU,
            => return setoptPointers(data, option, parg),
            CURLOPT_STREAM_DEPENDS,
            CURLOPT_STREAM_DEPENDS_E,
            => return CURLE_OK,
            else => {},
        }
        return setoptCptr(data, option, @ptrCast(parg));
    } else if (option < CURLOPTTYPE_OFF_T) {
        return setoptFunc(data, option, parg);
    } else if (option < CURLOPTTYPE_BLOB) {
        return setoptOfft(data, option, oarg);
    }
    return setoptBlob(data, option, castOptPtr(curl_blob, parg));
}

test "Curl_setblobopt copy and nocopy" {
    var blob_slot: ?*curl_blob = null;
    defer _ = Curl_setblobopt(&blob_slot, null);

    var sample = [_]u8{ 0xde, 0xad, 0xbe, 0xef };
    const in_copy = curl_blob{
        .data = &sample,
        .len = sample.len,
        .flags = CURL_BLOB_COPY,
    };
    try std.testing.expectEqual(CURLE_OK, Curl_setblobopt(&blob_slot, &in_copy));
    try std.testing.expect(blob_slot != null);
    try std.testing.expect(blob_slot.?.data.? != @as([*]u8, &sample));
    try std.testing.expectEqualSlices(u8, &sample, blob_slot.?.data.?[0..sample.len]);

    const in_nocopy = curl_blob{
        .data = &sample,
        .len = sample.len,
        .flags = CURL_BLOB_NOCOPY,
    };
    try std.testing.expectEqual(CURLE_OK, Curl_setblobopt(&blob_slot, &in_nocopy));
    try std.testing.expect(blob_slot != null);
    try std.testing.expectEqual(@as(?[*]u8, &sample), blob_slot.?.data);

    const invalid = curl_blob{
        .data = null,
        .len = 4,
        .flags = CURL_BLOB_COPY,
    };
    try std.testing.expectEqual(CURLE_BAD_FUNCTION_ARGUMENT, Curl_setblobopt(&blob_slot, &invalid));
}

test "protocol2num parsing" {
    var mask: curl_prot_t = 0;
    try std.testing.expectEqual(CURLE_OK, protocol2num("http,ftp", &mask));
    try std.testing.expect((mask & CURLPROTO_HTTP) != 0);
    if (use_ssl) {
        try std.testing.expectEqual(CURLE_OK, protocol2num("http,https", &mask));
        try std.testing.expect((mask & CURLPROTO_HTTPS) != 0);
    } else {
        try std.testing.expectEqual(CURLE_UNSUPPORTED_PROTOCOL, protocol2num("http,https", &mask));
    }

    try std.testing.expectEqual(CURLE_OK, protocol2num("ALL", &mask));
    try std.testing.expectEqual(~@as(curl_prot_t, 0), mask);

    try std.testing.expectEqual(CURLE_UNSUPPORTED_PROTOCOL, protocol2num("notaprotocol", &mask));
    try std.testing.expectEqual(CURLE_BAD_FUNCTION_ARGUMENT, protocol2num(",,,", &mask));
    try std.testing.expectEqual(CURLE_BAD_FUNCTION_ARGUMENT, protocol2num(null, &mask));
}

test "valueRange clamping and validation" {
    var v: c_long = 500;
    try std.testing.expectEqual(CURLE_OK, valueRange(&v, 0, 1024, 4096));
    try std.testing.expectEqual(@as(c_long, 1024), v);

    v = 8192;
    try std.testing.expectEqual(CURLE_OK, valueRange(&v, 0, 1024, 4096));
    try std.testing.expectEqual(@as(c_long, 4096), v);

    v = -1;
    try std.testing.expectEqual(CURLE_BAD_FUNCTION_ARGUMENT, valueRange(&v, 0, 1024, 4096));
}
