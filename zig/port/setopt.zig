                Curl_setopt_set_i64(data, FIELD_HTTPAUTH, @intCast(CURLAUTH_AWS_SIGV4));
            } else {
                const cur: u32 = @intCast(Curl_setopt_get_i64(data, FIELD_HTTPAUTH));
                Curl_setopt_set_i64(data, FIELD_HTTPAUTH, cur & ~@as(u32, @intCast(CURLAUTH_AWS_SIGV4)));
            }
        },
        CURLOPT_HTTPSIG_KEY => result = Curl_setstropt(data, STRING_HTTPSIG_KEY, ptr),
        CURLOPT_HTTPSIG_KEYID => result = Curl_setstropt(data, STRING_HTTPSIG_KEYID, ptr),
        CURLOPT_HTTPSIG_HEADERS => result = Curl_setstropt(data, STRING_HTTPSIG_HEADERS, ptr),
        CURLOPT_REFERER => {
