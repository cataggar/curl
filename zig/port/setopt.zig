fn valueRange(value: *c_long, below_error: c_long, min: c_long, max: c_long) CURLcode {
    if (value.* < below_error) {
        return CURLE_BAD_FUNCTION_ARGUMENT;
    } else if (value.* < min) {
        value.* = min;
    } else if (value.* > max) {
        value.* = max;
    }
    return CURLE_OK;
}

