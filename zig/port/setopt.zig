        },
        CURLOPT_RESUME_FROM => {
            if (arg < -1) return CURLE_BAD_FUNCTION_ARGUMENT;
            Curl_setopt_set_i64(data, FIELD_SET_RESUME_FROM, arg);
        },
        CURLOPT_UPLOAD_FLAGS => Curl_setopt_set_i64(data, FIELD_UPLOAD_FLAGS, arg & 0xff),
        CURLOPT_MIME_OPTIONS => Curl_setopt_set_bit(data, BIT_MIME_FORMESCAPE, (arg & CURLMIMEOPT_FORMESCAPE) != 0),
        CURLOPT_HSTS_CTRL => {
            if (!enable_hsts) return CURLE_UNKNOWN_OPTION;
            if ((arg & CURLHSTS_ENABLE) != 0) {
                if (Curl_setopt_get_ptr(data, PTR_DATA_HSTS) == null) {
                    const hsts = Curl_hsts_init() orelse return CURLE_OUT_OF_MEMORY;
                    Curl_setopt_set_ptr(data, PTR_DATA_HSTS, hsts);
                }
            } else if (Curl_setopt_get_ptr(data, PTR_DATA_SHARE) == null or Curl_setopt_get_ptr(data, PTR_SHARE_HSTS) == null) {
                if (setoptGetPtrRef(?*anyopaque, data, PTR_REF_DATA_HSTS)) |hsts_ref| {
                    Curl_hsts_cleanup(hsts_ref);
                }
                if (setoptGetPtr(curl_slist, data, PTR_STATE_HSTSLIST)) |list| {
                    curl_slist_free_all(list);
                    Curl_setopt_set_ptr(data, PTR_STATE_HSTSLIST, null);
                }
            } else {
                Curl_setopt_set_ptr(data, PTR_DATA_HSTS, null);
            }
        },
        CURLOPT_ALTSVC_CTRL => {
            const asi_ref = setoptGetPtrRef(?*anyopaque, data, PTR_REF_DATA_ASI) orelse return CURLE_BAD_FUNCTION_ARGUMENT;
            return Curl_altsvc_ctrl(asi_ref, arg);
        },
        CURLOPT_GSSAPI_DELEGATION => {
            if (!use_windows_sspi and !use_gssapi) return CURLE_UNKNOWN_OPTION;
            Curl_setopt_set_i64(
                data,
                FIELD_GSSAPI_DELEGATION,
                arg & (CURLGSSAPI_DELEGATION_POLICY_FLAG | CURLGSSAPI_DELEGATION_FLAG),
            );
        },
        else => return CURLE_UNKNOWN_OPTION,
    }
    return CURLE_OK;
}

