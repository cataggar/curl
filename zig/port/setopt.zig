pub export fn Curl_setblobopt(blobp: *?*curl_blob, blob: ?*const curl_blob) callconv(.c) CURLcode {
    if (blobp.*) |prev| {
        mem.freeTyped(prev);
        blobp.* = null;
    }

    if (blob) |b| {
        if (b.data == null or b.len == 0 or b.len > CURL_MAX_INPUT_LENGTH) {
            return CURLE_BAD_FUNCTION_ARGUMENT;
        }
        const copy = (b.flags & CURL_BLOB_COPY) != 0;
        const alloc_size = @sizeOf(curl_blob) + (if (copy) b.len else 0);
        const raw = mem.malloc(alloc_size) orelse return CURLE_OUT_OF_MEMORY;
        const nblob: *curl_blob = @ptrCast(@alignCast(raw));
        nblob.* = b.*;
        if (copy) {
            const dst = raw + @sizeOf(curl_blob);
            const src = b.data.?;
            @memcpy(dst[0..b.len], src[0..b.len]);
            nblob.data = dst;
        }
        blobp.* = nblob;
    }
    return CURLE_OK;
}

fn setstroptUserpwd(option: ?[*:0]const u8, userp: *?[*:0]u8, passwdp: *?[*:0]u8) CURLcode {
    var user: ?[*:0]u8 = null;
    var passwd: ?[*:0]u8 = null;

    if (option) |opt| {
        const len = std.mem.len(opt);
        if (len > CURL_MAX_INPUT_LENGTH) {
            return CURLE_BAD_FUNCTION_ARGUMENT;
        }
        const result = Curl_parse_login_details(opt, len, &user, &passwd, null);
