fn changeproxy(data: *Curl_easy) void {
    Curl_auth_digest_cleanup(Curl_setopt_get_ptr_ref(data, PTR_REF_STATE_PROXYDIGEST));
    if (setoptGetPtrRef([16]u8, data, PTR_REF_STATE_AUTHPROXY)) |authproxy_ptr| {
        authproxy_ptr.* = @splat(0);
    }
}

fn setoptLongProxy(data: *Curl_easy, option: CURLoption, arg: c_long) CURLcode {
    switch (option) {
        CURLOPT_PROXYPORT => {
            if (arg < 0 or arg > std.math.maxInt(u16)) return CURLE_BAD_FUNCTION_ARGUMENT;
            if (arg != Curl_setopt_get_i64(data, FIELD_PROXYPORT)) {
                changeproxy(data);
            }
            Curl_setopt_set_i64(data, FIELD_PROXYPORT, arg);
        },
        CURLOPT_PROXYAUTH => return httpauth(data, true, @bitCast(arg)),
        CURLOPT_PROXYTYPE => {
            if (arg < CURLPROXY_HTTP or arg > CURLPROXY_HTTPS3) return CURLE_BAD_FUNCTION_ARGUMENT;
            if (!use_proxy_http3 and arg == CURLPROXY_HTTPS3) return CURLE_NOT_BUILT_IN;
            Curl_setopt_set_i64(data, FIELD_PROXYTYPE, arg);
        },
        CURLOPT_SOCKS5_AUTH => {
            const auth: c_ulong = @bitCast(arg);
            if ((auth & ~(CURLAUTH_BASIC | CURLAUTH_GSSAPI | CURLAUTH_ONLY)) != 0) {
                return CURLE_NOT_BUILT_IN;
            }
            if ((auth & CURLAUTH_ONLY) != 0 and (auth & (CURLAUTH_BASIC | CURLAUTH_GSSAPI)) == 0) {
                return CURLE_BAD_FUNCTION_ARGUMENT;
            }
            Curl_setopt_set_i64(data, FIELD_SOCKS5AUTH, @intCast(auth & (CURLAUTH_BASIC | CURLAUTH_GSSAPI)));
            Curl_setopt_set_bit(data, BIT_SOCKS5_AUTH_ONLY, (auth & CURLAUTH_ONLY) != 0);
        },
        else => return CURLE_UNKNOWN_OPTION,
    }
    return CURLE_OK;
}

