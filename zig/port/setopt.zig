        CURLOPT_MAIL_AUTH => return Curl_setstropt(data, STRING_MAIL_AUTH, ptr),
        CURLOPT_SASL_AUTHZID => return Curl_setstropt(data, STRING_SASL_AUTHZID, ptr),
        CURLOPT_RTSP_SESSION_ID => {
            if (Curl_setopt_get_ptr_ref(data, PTR_REF_STATE_RTSP_SESSION_ORIGIN)) |origin_ref| {
                Curl_peer_unlink(origin_ref);
            }
            return Curl_setstropt(data, STRING_RTSP_SESSION_ID, ptr);
        },
        CURLOPT_RTSP_STREAM_URI => return Curl_setstropt(data, STRING_RTSP_STREAM_URI, ptr),
