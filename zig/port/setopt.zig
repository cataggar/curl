fn protocol2num(str_in: ?[*:0]const u8, val: *curl_prot_t) CURLcode {
    val.* = 0;
    var str = str_in orelse return CURLE_BAD_FUNCTION_ARGUMENT;

    if (primitives.curl_strequal(str, "all") != 0) {
        val.* = ~@as(curl_prot_t, 0);
        return CURLE_OK;
    }

    while (true) {
        const token: [*:0]const u8 = str;
        var tlen: usize = 0;
        while (token[tlen] != 0 and token[tlen] != ',') : (tlen += 1) {}
        const has_comma = token[tlen] == ',';

        if (tlen > 0) {
            const h = protocol_version_mime.Curl_getn_scheme(token, tlen) orelse return CURLE_UNSUPPORTED_PROTOCOL;
            if (h.run == null) {
                return CURLE_UNSUPPORTED_PROTOCOL;
            }
            val.* |= h.protocol;
        }

        if (!has_comma) break;
        str = token + (tlen + 1);
    }

    if (val.* == 0) {
        return CURLE_BAD_FUNCTION_ARGUMENT;
    }
    return CURLE_OK;
}

fn httpauth(data: *Curl_easy, proxy: bool, auth_in: c_ulong) CURLcode {
    var auth = auth_in;
    if (auth != CURLAUTH_NONE) {
        var bitcheck: u5 = 0;
        var authbits = false;
        if ((auth & CURLAUTH_DIGEST_IE) != 0) {
            auth |= CURLAUTH_DIGEST;
            auth &= ~CURLAUTH_DIGEST_IE;
        }

        if (!use_ntlm) {
            auth &= ~CURLAUTH_NTLM;
        }
        if (!use_spnego) {
            auth &= ~CURLAUTH_NEGOTIATE;
        }

        while (bitcheck < 31) : (bitcheck += 1) {
            if ((auth & (@as(c_ulong, 1) << bitcheck)) != 0) {
                authbits = true;
                break;
            }
        }
        if (!authbits) {
            return CURLE_NOT_BUILT_IN;
        }
    }
    const auth_u32: u32 = @truncate(auth);
    if (proxy) {
        Curl_setopt_set_i64(data, FIELD_PROXYAUTH, @intCast(auth_u32));
    } else {
        Curl_setopt_set_i64(data, FIELD_HTTPAUTH, @intCast(auth_u32));
    }
    return CURLE_OK;
}

fn setoptHttpVersion(data: *Curl_easy, arg: c_long) CURLcode {
    switch (arg) {
        CURL_HTTP_VERSION_NONE,
        CURL_HTTP_VERSION_1_0,
        CURL_HTTP_VERSION_1_1,
        => {},
        CURL_HTTP_VERSION_2_0,
        CURL_HTTP_VERSION_2TLS,
        CURL_HTTP_VERSION_2_PRIOR_KNOWLEDGE,
        => {
            if (!use_http2) return CURLE_UNSUPPORTED_PROTOCOL;
        },
        CURL_HTTP_VERSION_3,
        CURL_HTTP_VERSION_3ONLY,
        => {
            if (!use_http3) return CURLE_NOT_BUILT_IN;
        },
        else => {
            if (arg < CURL_HTTP_VERSION_NONE) {
                return CURLE_BAD_FUNCTION_ARGUMENT;
            }
            return CURLE_UNSUPPORTED_PROTOCOL;
        },
    }
    Curl_setopt_set_i64(data, FIELD_HTTPWANT, @as(u8, @intCast(arg)));
    return CURLE_OK;
}

pub export fn Curl_setopt_SSLVERSION(data: *Curl_easy, option: CURLoption, arg: c_long) callconv(.c) CURLcode {
    if (!use_ssl) {
        return CURLE_NOT_BUILT_IN;
    }
    var version: c_long = arg & 0xffff;
    const version_max_u: c_ulong = @as(c_ulong, @bitCast(arg)) & 0xffff0000;
    const version_max: c_long = @bitCast(version_max_u);

    if (version < CURL_SSLVERSION_DEFAULT or
        version == CURL_SSLVERSION_SSLv2 or
        version == CURL_SSLVERSION_SSLv3 or
        version >= CURL_SSLVERSION_LAST or
        version_max < CURL_SSLVERSION_MAX_NONE or
        version_max >= CURL_SSLVERSION_MAX_LAST)
    {
        return CURLE_BAD_FUNCTION_ARGUMENT;
    }
    if (version == CURL_SSLVERSION_DEFAULT) {
        version = CURL_SSLVERSION_TLSv1_2;
    }

    if (option != CURLOPT_SSLVERSION) {
        Curl_setopt_set_i64(data, FIELD_PROXY_SSL_VERSION, version);
        Curl_setopt_set_i64(data, FIELD_PROXY_SSL_VERSION_MAX, version_max);
    } else {
        Curl_setopt_set_i64(data, FIELD_SSL_VERSION, version);
        Curl_setopt_set_i64(data, FIELD_SSL_VERSION_MAX, version_max);
    }
    return CURLE_OK;
}

