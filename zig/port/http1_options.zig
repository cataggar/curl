fn trim_line(parser: *h1_req_parser, options: c_int) CURLcode {
    const line = parser.line orelse return CURLE_URL_MALFORMAT;
    if (parser.line_len > 0) {
        if (line[parser.line_len - 1] == '\n')
            parser.line_len -= 1;
        if (parser.line_len > 0) {
            if (line[parser.line_len - 1] == '\r') {
                parser.line_len -= 1;
            } else if ((options & H1_PARSE_OPT_STRICT) != 0) {
                return CURLE_URL_MALFORMAT;
            }
        } else if ((options & H1_PARSE_OPT_STRICT) != 0) {
            return CURLE_URL_MALFORMAT;
        }
    } else if ((options & H1_PARSE_OPT_STRICT) != 0) {
        return CURLE_URL_MALFORMAT;
    }

    if (parser.line_len > parser.max_line_len) {
        return CURLE_URL_MALFORMAT;
    }
    if (std.mem.indexOfAny(u8, line[0..parser.line_len], "\r\n\x00") != null) {
        return CURLE_URL_MALFORMAT;
    }
    return CURLE_OK;
}

fn detect_line(parser: *h1_req_parser, buf: [*]const u8, buflen: usize, pnread: *usize) CURLcode {
    pnread.* = 0;
    if (std.mem.indexOfScalar(u8, buf[0..buflen], '\n')) |idx| {
        parser.line = buf;
        parser.line_len = idx + 1;
        pnread.* = parser.line_len;
        return CURLE_OK;
    }
    return CURLE_AGAIN;
}

fn next_line(parser: *h1_req_parser, buf: [*]const u8, buflen: usize, options: c_int, pnread: *usize) CURLcode {
    pnread.* = 0;
    if (parser.line != null) {
        parser.line = null;
        parser.line_len = 0;
        containers.curlx_dyn_reset(&parser.scratch);
    }

    var result = detect_line(parser, buf, buflen, pnread);
    if (result == CURLE_OK) {
        if (containers.curlx_dyn_len(&parser.scratch) > 0) {
            result = containers.curlx_dyn_addn(&parser.scratch, parser.line, parser.line_len);
            if (result != CURLE_OK)
                return result;
            parser.line = containers.curlx_dyn_ptr(&parser.scratch);
            parser.line_len = containers.curlx_dyn_len(&parser.scratch);
        }
        result = trim_line(parser, options);
        if (result != CURLE_OK)
            return result;
    } else if (result == CURLE_AGAIN) {
        result = containers.curlx_dyn_addn(&parser.scratch, buf, buflen);
        pnread.* = buflen;
    }
    return result;
}

fn start_req(
    parser: *h1_req_parser,
    scheme_default: ?[*:0]const u8,
    custom_method: ?[*:0]const u8,
    options: c_int,
) CURLcode {
    if (!in_libcurl) return CURLE_NOT_BUILT_IN;

    const line = parser.line orelse return CURLE_URL_MALFORMAT;
    const line_len = parser.line_len;

    var p_idx: usize = 0;
    var found_p = false;
    if (custom_method) |cm| {
        const cm_len = std.mem.len(cm);
        if (cm_len > 0 and line_len >= cm_len and std.mem.eql(u8, cm[0..cm_len], line[0..cm_len])) {
            p_idx = cm_len;
            found_p = true;
        }
    }
    if (!found_p) {
        const sp_idx = std.mem.indexOfScalar(u8, line[0..line_len], ' ') orelse return CURLE_URL_MALFORMAT;
        if (sp_idx == 0) return CURLE_URL_MALFORMAT;
        p_idx = sp_idx;
    }

    const m: [*]const u8 = line;
    const m_len: usize = p_idx;
    if (p_idx + 1 > line_len) return CURLE_URL_MALFORMAT;
    const target: [*]const u8 = line + p_idx + 1;
    var target_len: usize = 0;
    var hv_len: usize = 0;

    var i: usize = line_len;
    while (i > m_len) {
        i -= 1;
        if (line[i] == ' ') {
            hv_len = line_len - (i + 1);
            if (i > p_idx + 1) {
                target_len = i - (p_idx + 1);
            }
            break;
        }
    }
    if (target_len == 0 or hv_len == 0)
        return CURLE_URL_MALFORMAT;

    var scheme: ?[*]const u8 = null;
    var scheme_len: usize = 0;
    var authority: ?[*]const u8 = null;
    var authority_len: usize = 0;
    var path: ?[*]const u8 = null;
    var path_len: usize = 0;

    var url: ?*anyopaque = null;
    defer curl_url_cleanup(url);

    if (target_len == 1 and target[0] == '*') {
        path = target;
        path_len = target_len;
    } else if (m_len == 7 and std.mem.eql(u8, m[0..m_len], "CONNECT")) {
        authority = target;
        authority_len = target_len;
    } else if (target[0] == '/') {
        path = target;
        path_len = target_len;
    } else {
        var tmp: [H1_MAX_URL_LEN]u8 = undefined;
        path = target;
        path_len = target_len;

        if (target_len >= tmp.len)
            return CURLE_URL_MALFORMAT;
        @memcpy(tmp[0..target_len], target[0..target_len]);
        tmp[target_len] = 0;
        const tmp_z: [*:0]const u8 = tmp[0..target_len :0];

        if (Curl_is_absolute_url(tmp_z, null, 0, false) != 0) {
            url = curl_url();
            if (url == null)
                return CURLE_OUT_OF_MEMORY;
            var url_options: c_uint = CURLU_NON_SUPPORT_SCHEME | CURLU_PATH_AS_IS | CURLU_NO_DEFAULT_PORT;
            if ((options & H1_PARSE_OPT_STRICT) == 0)
                url_options |= CURLU_ALLOW_SPACE;
            if (curl_url_set(url, CURLUPART_URL, tmp_z, url_options) != 0)
                return CURLE_URL_MALFORMAT;
        }

        if (url == null and (options & H1_PARSE_OPT_STRICT) != 0)
            return CURLE_URL_MALFORMAT;
    }

    if (url != null) {
        return Curl_http_req_make2(&parser.req, m, m_len, url, scheme_default);
    } else {
        if (scheme == null) {
            if (scheme_default) |sd| {
                scheme = sd;
                scheme_len = std.mem.len(sd);
            }
        }
        return Curl_http_req_make(&parser.req, m, m_len, scheme, scheme_len, authority, authority_len, path, path_len);
    }
}

pub export fn Curl_h1_req_parse_read(
    parser: *h1_req_parser,
    buf_opt: ?[*]const u8,
    buflen_in: usize,
    scheme_default: ?[*:0]const u8,
    custom_method: ?[*:0]const u8,
    options: c_int,
    pnread: *usize,
) callconv(.c) CURLcode {
    if (!in_libcurl) return CURLE_NOT_BUILT_IN;

    pnread.* = 0;
    var buf = buf_opt orelse return CURLE_BAD_FUNCTION_ARGUMENT;
    var buflen = buflen_in;
    var result: CURLcode = CURLE_OK;
    var nread: usize = 0;

    while (parser.done == 0) {
        result = next_line(parser, buf, buflen, options, &nread);
        if (result != CURLE_OK) {
            if (result == CURLE_AGAIN)
                result = CURLE_OK;
            break;
        }

        pnread.* += nread;
        buf += nread;
        buflen -= nread;

        if (parser.line == null) {
            if (buflen == 0) break;
        } else if (parser.req == null) {
            result = start_req(parser, scheme_default, custom_method, options);
            if (result != CURLE_OK) break;
        } else if (parser.line_len == 0) {
            if (parser.req == null) {
                result = CURLE_URL_MALFORMAT;
                break;
            }
            parser.done = 1;
            containers.curlx_dyn_reset(&parser.scratch);
        } else {
            result = Curl_dynhds_h1_add_line(&parser.req.?.headers, parser.line.?, parser.line_len);
            if (result != CURLE_OK) break;
        }
    }

    return result;
}

pub export fn Curl_h1_req_write_head(
    req: *httpreq,
    http_minor: c_int,
    dbuf: *containers.dynbuf,
) callconv(.c) CURLcode {
    if (!in_libcurl) return CURLE_NOT_BUILT_IN;

    const method_z: [*:0]const u8 = @ptrCast(&req.method[0]);
    var result = containers.curlx_dyn_add(dbuf, method_z);
    if (result != CURLE_OK) return result;
    result = containers.curlx_dyn_addn(dbuf, " ", 1);
    if (result != CURLE_OK) return result;
    if (req.scheme) |s| {
        result = containers.curlx_dyn_add(dbuf, s);
        if (result != CURLE_OK) return result;
        result = containers.curlx_dyn_addn(dbuf, "://", 3);
        if (result != CURLE_OK) return result;
    }
    if (req.authority) |a| {
        result = containers.curlx_dyn_add(dbuf, a);
        if (result != CURLE_OK) return result;
    }
    if (req.path) |p| {
        result = containers.curlx_dyn_add(dbuf, p);
        if (result != CURLE_OK) return result;
    }
    var tail_buf: [32]u8 = undefined;
    const tail = std.fmt.bufPrint(&tail_buf, " HTTP/1.{d}\r\n", .{http_minor}) catch return CURLE_OUT_OF_MEMORY;
    result = containers.curlx_dyn_addn(dbuf, tail.ptr, tail.len);
    if (result != CURLE_OK) return result;

    result = Curl_dynhds_h1_dprint(&req.headers, dbuf);
    if (result != CURLE_OK) return result;

    return containers.curlx_dyn_addn(dbuf, "\r\n", 2);
}

