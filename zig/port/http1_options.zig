extern fn Curl_infof(data: ?*anyopaque, fmt: [*:0]const u8, ...) callconv(.c) void;
extern fn Curl_trc_cf_infof(data: ?*anyopaque, cf: ?*const anyopaque, fmt: [*:0]const u8, ...) callconv(.c) void;

fn capsule_encode_varint_buf(buf: [*]u8, value: u64) usize {
    if (value <= 0x3F) {
        buf[0] = @intCast(value);
        return 1;
    } else if (value <= 0x3FFF) {
        const encoded: u16 = (@as(u16, @intCast(value)) & 0x3FFF) | 0x4000;
        std.mem.writeInt(u16, buf[0..2], encoded, .big);
        return 2;
    } else if (value <= 0x3FFFFFFF) {
        const encoded: u32 = (@as(u32, @intCast(value)) & 0x3FFFFFFF) | 0x80000000;
        std.mem.writeInt(u32, buf[0..4], encoded, .big);
        return 4;
    } else {
        const encoded: u64 = (value & 0x3FFFFFFFFFFFFFFF) | 0xC000000000000000;
        std.mem.writeInt(u64, buf[0..8], encoded, .big);
        return 8;
    }
}

fn capsule_peek_u8(recvbufq: *anyopaque, offset: usize, pbyte: *u8) CURLcode {
    var peek: ?[*]const u8 = null;
    var peeklen: usize = 0;
    if (!Curl_bufq_peek_at(recvbufq, offset, &peek, &peeklen) or peeklen == 0)
        return CURLE_AGAIN;
    pbyte.* = peek.?[0];
    return CURLE_OK;
}

fn capsule_decode_varint_at(
    recvbufq: *anyopaque,
    offset: usize,
    pvalue: *u64,
    pconsumed: *usize,
) CURLcode {
    var first_byte: u8 = 0;
    var byte: u8 = 0;

    var result = capsule_peek_u8(recvbufq, offset, &first_byte);
    if (result != CURLE_OK)
        return result;

    const nbytes: usize = @as(usize, 1) << @intCast(first_byte >> 6);
    var value: u64 = first_byte & 0x3F;

    var i: usize = 1;
    while (i < nbytes) : (i += 1) {
        result = capsule_peek_u8(recvbufq, offset + i, &byte);
        if (result != CURLE_OK)
            return result;
        value = (value << 8) | @as(u64, byte);
    }

    pvalue.* = value;
    pconsumed.* = nbytes;
    return CURLE_OK;
}

pub export fn capsule_encap_udp_hdr(hdr: [*]u8, hdrlen: usize, payload_len: usize) callconv(.c) usize {
    if (hdrlen < HTTP_CAPSULE_HEADER_MAX_SIZE)
        return 0;
    var off: usize = 0;
    hdr[off] = 0;
    off += 1;
    off += capsule_encode_varint_buf(hdr + off, @as(u64, payload_len) + 1);
    hdr[off] = 0;
    off += 1;
    return off;
}

pub export fn Curl_capsule_encap_udp_datagram(
    q: *anyopaque,
    buf: *const anyopaque,
    blen: usize,
) callconv(.c) CURLcode {
    if (!in_libcurl) return CURLE_NOT_BUILT_IN;

    var hdr: [HTTP_CAPSULE_HEADER_MAX_SIZE]u8 = undefined;
    var nwritten: usize = 0;

    const hdr_len = capsule_encap_udp_hdr(&hdr, hdr.len, blen);
    if (hdr_len == 0)
        return CURLE_FAILED_INIT;

    var result = Curl_bufq_write(q, &hdr, hdr_len, &nwritten);
    if (result == CURLE_OK and nwritten != hdr_len)
        return CURLE_WRITE_ERROR;
    if (result == CURLE_OK) {
        const buf_bytes: [*]const u8 = @ptrCast(buf);
        result = Curl_bufq_write(q, buf_bytes, blen, &nwritten);
        if (result == CURLE_OK and nwritten != blen)
            return CURLE_WRITE_ERROR;
    }
    if (result == CURLE_AGAIN)
        return CURLE_WRITE_ERROR;
    return result;
}

pub export fn Curl_capsule_process_udp_raw(
    cf: ?*anyopaque,
    data: ?*anyopaque,
    recvbufq: *anyopaque,
    buf: [*]u8,
    len: usize,
    err: *CURLcode,
) callconv(.c) usize {
    if (!in_libcurl) {
        err.* = CURLE_NOT_BUILT_IN;
        return 0;
    }

    var context_id: ?[*]const u8 = null;
    var capsule_type: ?[*]const u8 = null;
    var read_size: usize = 0;
    var varint_len: usize = 0;
    var capsule_length: u64 = 0;
    var offset: usize = 0;
    var payload_len: usize = 0;
    var bytes_read: usize = 0;
    var result: CURLcode = CURLE_OK;

    if (len == 0) {
        err.* = CURLE_BAD_FUNCTION_ARGUMENT;
        return 0;
    }

    if (Curl_bufq_is_empty(recvbufq)) {
        err.* = CURLE_AGAIN;
        return 0;
    }

    if (!Curl_bufq_peek(recvbufq, &capsule_type, &read_size) or read_size == 0) {
        err.* = CURLE_AGAIN;
        return 0;
    }

    if (capsule_type.?[0] != 0) {
        Curl_infof(data, "Error! Invalid capsule type: %d", @as(c_int, capsule_type.?[0]));
        Curl_bufq_skip(recvbufq, 1);
        err.* = CURLE_RECV_ERROR;
        return 0;
    }

    offset = 1;
    result = capsule_decode_varint_at(recvbufq, offset, &capsule_length, &varint_len);
    if (result == CURLE_AGAIN) {
        err.* = CURLE_AGAIN;
        return 0;
    } else if (result != CURLE_OK) {
        err.* = CURLE_RECV_ERROR;
        return 0;
    }
    offset += varint_len;

    if (!Curl_bufq_peek_at(recvbufq, offset, &context_id, &read_size) or read_size == 0) {
        err.* = CURLE_AGAIN;
        return 0;
    }

    if (context_id.?[0] != 0) {
        Curl_infof(data, "Error! Invalid context ID: %02x", @as(c_uint, context_id.?[0]));
        Curl_bufq_skip(recvbufq, offset + 1);
        err.* = CURLE_RECV_ERROR;
        return 0;
    }
    offset += 1;

    if (capsule_length == 0) {
        Curl_infof(data, "Error! Invalid capsule length: 0");
        Curl_bufq_skip(recvbufq, offset);
        err.* = CURLE_RECV_ERROR;
        return 0;
    }
    if (capsule_length - 1 > @as(u64, std.math.maxInt(usize) - offset)) {
        Curl_infof(data, "Error! Capsule length too large: %lld", @as(c_longlong, @bitCast(capsule_length)));
        err.* = CURLE_RECV_ERROR;
        return 0;
    }
    payload_len = @intCast(capsule_length - 1);

    if (payload_len > len) {
        Curl_infof(data, "UDP payload does not fit destination buffer: %zu > %zu", payload_len, len);
        Curl_bufq_skip(recvbufq, offset + payload_len);
        err.* = CURLE_RECV_ERROR;
        return 0;
    }

    if (Curl_bufq_len(recvbufq) < offset + payload_len) {
        if (Curl_bufq_is_full(recvbufq)) {
            Curl_infof(data, "Error! Capsule does not fit the receive buffer: %zu", payload_len);
            err.* = CURLE_RECV_ERROR;
            return 0;
        }
        err.* = CURLE_AGAIN;
        return 0;
    }

    Curl_bufq_skip(recvbufq, offset);
    if (payload_len == 0) {
        err.* = CURLE_OK;
        return 0;
    }
    result = Curl_bufq_read(recvbufq, buf, payload_len, &bytes_read);
    if (result != CURLE_OK or bytes_read != payload_len) {
        Curl_infof(data, "Error! Read less than expected %zu %zu", payload_len, bytes_read);
        err.* = CURLE_RECV_ERROR;
        return 0;
    }

    if (cf != null and data != null) {
        Curl_trc_cf_infof(
            data,
            cf,
            "Processed UDP capsule raw: size=%zu length_left %zu",
            payload_len,
            Curl_bufq_len(recvbufq),
        );
    }
    err.* = CURLE_OK;
    return bytes_read;
}

