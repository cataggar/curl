pub export fn Curl_ed25519_sign(
    key: ?[*]const u8,
    keylen: usize,
    msg: ?[*]const u8,
    msglen: usize,
    sig: ?[*]u8,
    siglen: ?*usize,
) callconv(.c) CURLcode {
    const k = key orelse return CURLE_BAD_FUNCTION_ARGUMENT;
    const s = sig orelse return CURLE_BAD_FUNCTION_ARGUMENT;
    const sl = siglen orelse return CURLE_BAD_FUNCTION_ARGUMENT;
    if (keylen != 32 or sl.* < 64) {
        return CURLE_BAD_FUNCTION_ARGUMENT;
    }
    const m_slice: []const u8 = if (msglen == 0) &[_]u8{} else (msg orelse return CURLE_BAD_FUNCTION_ARGUMENT)[0..msglen];

    var seed: [32]u8 = undefined;
    @memcpy(&seed, k[0..32]);
    defer std.crypto.secureZero(u8, &seed);

    const kp = std.crypto.sign.Ed25519.KeyPair.generateDeterministic(seed) catch {
        return CURLE_BAD_FUNCTION_ARGUMENT;
    };
    const signature = kp.sign(m_slice, null) catch {
        return CURLE_BAD_FUNCTION_ARGUMENT;
    };
    const sig_bytes = signature.toBytes();
    @memcpy(s[0..64], &sig_bytes);
    sl.* = 64;
    return CURLE_OK;
}

