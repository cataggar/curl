pub const CREDS_NONE: u8 = 0;
pub const CREDS_URL: u8 = 1;
pub const CREDS_OPTION: u8 = 2;
pub const CREDS_NETRC: u8 = 3;

const CURL_MAX_INPUT_LENGTH: usize = 8000000;

pub const Curl_creds = extern struct {
    user: [*:0]const u8,
    passwd: [*:0]const u8,
    oauth_bearer: [*:0]const u8,
    sasl_authzid: [*:0]const u8,
    sasl_service: [*:0]const u8,
    refcount: u32,
    source: u8,
    bufsize: usize,
    buf: [1]u8,
};

extern fn Curl_trc_multi(data: ?*anyopaque, fmt: [*:0]const u8, ...) callconv(.c) void;

pub export fn Curl_creds_create(
    user: ?[*:0]const u8,
    passwd: ?[*:0]const u8,
    oauth_bearer: ?[*:0]const u8,
    sasl_authzid: ?[*:0]const u8,
    sasl_service: ?[*:0]const u8,
    source: u8,
    pcreds: *?*Curl_creds,
) callconv(.c) CURLcode {
    const ulen: usize = if (user) |s| std.mem.len(s) else 0;
    const plen: usize = if (passwd) |s| std.mem.len(s) else 0;
    const olen: usize = if (oauth_bearer) |s| std.mem.len(s) else 0;
    const salen: usize = if (sasl_authzid) |s| std.mem.len(s) else 0;
    const sslen: usize = if (sasl_service) |s| std.mem.len(s) else 0;

    Curl_creds_unlink(pcreds);

    // Everything empty/NULL, this is the NULL credential
    if (user == null and passwd == null and olen == 0 and salen == 0 and sslen == 0) {
        pcreds.* = null;
        return CURLE_OK;
    }

    if ((ulen > CURL_MAX_INPUT_LENGTH) or
        (plen > CURL_MAX_INPUT_LENGTH) or
        (olen > CURL_MAX_INPUT_LENGTH) or
        (salen > CURL_MAX_INPUT_LENGTH) or
        (sslen > CURL_MAX_INPUT_LENGTH))
    {
        return CURLE_BAD_FUNCTION_ARGUMENT;
    }

    // null-terminator for user already part of struct
    const bufsize: usize = ulen + plen + 1 + olen + 1 + salen + 1 + sslen + 1;
    const raw = mem.calloc(1, @sizeOf(Curl_creds) + bufsize) orelse {
        return CURLE_OUT_OF_MEMORY;
    };
    const c: *Curl_creds = @ptrCast(@alignCast(raw));

    c.bufsize = bufsize;
    c.refcount = 1;
    c.source = source;

    const buf_base: [*]u8 = @as([*]u8, @ptrCast(c)) + @offsetOf(Curl_creds, "buf");
    c.user = @ptrCast(buf_base);
    if (ulen > 0)
        @memcpy(buf_base[0 .. ulen + 1], user.?[0 .. ulen + 1]);

    const passwd_ptr = buf_base + ulen + 1;
    c.passwd = @ptrCast(passwd_ptr);
    if (plen > 0)
        @memcpy(passwd_ptr[0 .. plen + 1], passwd.?[0 .. plen + 1]);

    const oauth_ptr = passwd_ptr + plen + 1;
    c.oauth_bearer = @ptrCast(oauth_ptr);
    if (olen > 0)
        @memcpy(oauth_ptr[0 .. olen + 1], oauth_bearer.?[0 .. olen + 1]);

    const authzid_ptr = oauth_ptr + olen + 1;
    c.sasl_authzid = @ptrCast(authzid_ptr);
    if (salen > 0)
        @memcpy(authzid_ptr[0 .. salen + 1], sasl_authzid.?[0 .. salen + 1]);

    const service_ptr = authzid_ptr + salen + 1;
    c.sasl_service = @ptrCast(service_ptr);
    if (sslen > 0)
        @memcpy(service_ptr[0 .. sslen + 1], sasl_service.?[0 .. sslen + 1]);

    pcreds.* = c;
    return CURLE_OK;
}

pub export fn Curl_creds_merge(
    user: ?[*:0]const u8,
    passwd: ?[*:0]const u8,
    creds_in: ?*Curl_creds,
    source: u8,
    pcreds_out: *?*Curl_creds,
) callconv(.c) CURLcode {
    var creds_out: ?*Curl_creds = null;
    const result = if (creds_in) |ci|
        Curl_creds_create(
            user orelse ci.user,
            passwd orelse ci.passwd,
            ci.oauth_bearer,
            ci.sasl_authzid,
            ci.sasl_service,
            source,
            &creds_out,
        )
    else
        Curl_creds_create(user, passwd, null, null, null, source, &creds_out);

    Curl_creds_link(pcreds_out, creds_out);
    Curl_creds_unlink(&creds_out);
    return result;
}

pub export fn Curl_creds_link(pdest: *?*Curl_creds, src: ?*Curl_creds) callconv(.c) void {
    if (pdest.* != src) {
        Curl_creds_unlink(pdest);
        pdest.* = src;
        if (src) |s| {
            s.refcount += 1;
        }
    }
}

pub export fn Curl_creds_unlink(pcreds_opt: ?*?*Curl_creds) callconv(.c) void {
    const pcreds = pcreds_opt orelse return;
    if (pcreds.*) |creds| {
        pcreds.* = null;
        if (creds.refcount > 0)
            creds.refcount -= 1;
        if (creds.refcount == 0) {
            const raw_bytes: [*]u8 = @ptrCast(creds);
            std.crypto.secureZero(u8, raw_bytes[0 .. @sizeOf(Curl_creds) + creds.bufsize]);
            mem.free(creds);
        }
    }
}

pub export fn Curl_creds_same(c1_opt: ?*Curl_creds, c2_opt: ?*Curl_creds) callconv(.c) bool {
    if (c1_opt == c2_opt) return true;
    const c1 = c1_opt orelse return false;
    const c2 = c2_opt orelse return false;
    return (primitives.Curl_timestrcmp(c1.user, c2.user) == 0) and
        (primitives.Curl_timestrcmp(c1.passwd, c2.passwd) == 0) and
        (primitives.Curl_timestrcmp(c1.oauth_bearer, c2.oauth_bearer) == 0) and
        (primitives.Curl_timestrcmp(c1.sasl_authzid, c2.sasl_authzid) == 0) and
        (primitives.Curl_timestrcmp(c1.sasl_service, c2.sasl_service) == 0);
}

pub export fn Curl_creds_equal(c1_opt: ?*Curl_creds, c2_opt: ?*Curl_creds) callconv(.c) bool {
    if (!Curl_creds_same(c1_opt, c2_opt)) return false;
    if (c1_opt == c2_opt) return true;
    const c1 = c1_opt orelse return false;
    const c2 = c2_opt orelse return false;
    return c1.source == c2.source;
}

pub export fn Curl_creds_trace(data: ?*anyopaque, creds_opt: ?*Curl_creds, msg: [*:0]const u8) callconv(.c) void {
    if (!in_libcurl) return;
    if (creds_opt) |creds| {
        const has_passwd: [*:0]const u8 = if (creds.passwd[0] != 0) "***" else "";
        const has_oauth: [*:0]const u8 = if (creds.oauth_bearer[0] != 0) "***" else "";
        Curl_trc_multi(
            data,
            "%s: user=%s, passwd=%s, sasl_authzid=%s, oauth_bearer=%s, source=%d",
            msg,
            creds.user,
            has_passwd,
            creds.sasl_authzid,
            has_oauth,
            @as(c_int, creds.source),
        );
    } else {
        Curl_trc_multi(data, "%s: -", msg);
    }
}

