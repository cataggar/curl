const darwin_c = struct {
    extern fn arc4random_buf(buf: [*]u8, nbytes: usize) callconv(.c) void;
};

var randseed_state = std.atomic.Value(u32).init(0);

fn weak_random(data: ?*anyopaque) u32 {
    var r: u32 = randseed_state.load(.monotonic);
    if (r == 0) {
        const now = curlx_time_net.curlx_now();
        const usec_u32: u32 = @truncate(@as(u64, @bitCast(@as(i64, now.tv_usec))));
        const sec_u32: u32 = @truncate(@as(u64, @bitCast(now.tv_sec)));
        r = usec_u32 ^ sec_u32;
        r = r +% @as(u32, @truncate(@intFromPtr(data)));
        if (r == 0) r = 1;
    }
    r = r *% 1103515245 +% 12345;
    randseed_state.store(r, .monotonic);
    return (r << 16) | ((r >> 16) & 0xFFFF);
}

fn fill_csprng(buf: []u8) bool {
    if (buf.len == 0) return true;
    if (builtin.os.tag == .windows) {
        return os_leaf.win32.curlx_win32_random(buf.ptr, buf.len) == CURLE_OK;
    } else if (builtin.os.tag.isDarwin()) {
        darwin_c.arc4random_buf(buf.ptr, buf.len);
        return true;
    } else if (builtin.os.tag == .linux) {
        var offset: usize = 0;
        while (offset < buf.len) {
            const rc = std.os.linux.getrandom(buf.ptr + offset, buf.len - offset, 0);
            switch (std.os.linux.errno(rc)) {
                .SUCCESS => {
                    if (rc == 0) return false;
                    offset += rc;
                },
                .INTR => continue,
                else => return false,
            }
        }
        return true;
    } else {
        return false;
    }
}

fn randit(data: ?*anyopaque, rnd: *u32) CURLcode {
    var bytes: [4]u8 = undefined;
    if (fill_csprng(&bytes)) {
        rnd.* = @bitCast(bytes);
        return CURLE_OK;
    }
    rnd.* = weak_random(data);
    return CURLE_OK;
}

pub export fn Curl_rand_bytes(
    data: ?*anyopaque,
    rnd_opt: ?[*]u8,
    num_in: usize,
) callconv(.c) CURLcode {
    const rnd = rnd_opt orelse return CURLE_BAD_FUNCTION_ARGUMENT;
    if (num_in == 0) return CURLE_BAD_FUNCTION_ARGUMENT;

    if (fill_csprng(rnd[0..num_in])) {
        return CURLE_OK;
    }

    var out = rnd;
    var num = num_in;
    var result: CURLcode = CURLE_BAD_FUNCTION_ARGUMENT;
    while (num > 0) {
        var r: u32 = 0;
        const left: usize = @min(num, @sizeOf(u32));
        result = randit(data, &r);
        if (result != CURLE_OK) return result;
        var rem = left;
        while (rem > 0) : (rem -= 1) {
            out[0] = @truncate(r & 0xFF);
            r >>= 8;
            out += 1;
            num -= 1;
        }
    }
    return result;
}

pub export fn Curl_rand_hex(
    data: ?*anyopaque,
    rnd_opt: ?[*]u8,
    num_in: usize,
) callconv(.c) CURLcode {
    const rnd = rnd_opt orelse return CURLE_BAD_FUNCTION_ARGUMENT;
    var buffer: [128]u8 = undefined;
    if ((num_in / 2 >= buffer.len) or (num_in & 1) == 0) {
        return CURLE_BAD_FUNCTION_ARGUMENT;
    }
    const num = num_in - 1;
    const half = num / 2;
    const result = Curl_rand_bytes(data, &buffer, half);
    if (result != CURLE_OK) return result;

    const ldigits = "0123456789abcdef";
    for (0..half) |i| {
        const b = buffer[i];
        rnd[i * 2] = ldigits[b >> 4];
        rnd[i * 2 + 1] = ldigits[b & 0x0F];
    }
    rnd[half * 2] = 0;
    return CURLE_OK;
}

const alnum_chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";

pub export fn Curl_rand_alnum(
    data: ?*anyopaque,
    rnd_opt: ?[*]u8,
    num_in: usize,
) callconv(.c) CURLcode {
    const rnd = rnd_opt orelse return CURLE_BAD_FUNCTION_ARGUMENT;
    if (num_in == 0) return CURLE_BAD_FUNCTION_ARGUMENT;

    const alnumspace: u32 = @intCast(alnum_chars.len);
    const limit: u32 = std.math.maxInt(u32) - (std.math.maxInt(u32) % alnumspace);
    var rem = num_in - 1;
    var out = rnd;

    while (rem > 0) : (rem -= 1) {
        var r: u32 = 0;
        while (true) {
            const result = randit(data, &r);
            if (result != CURLE_OK) return result;
            if (r < limit) break;
        }
        out[0] = alnum_chars[r % alnumspace];
        out += 1;
    }
    out[0] = 0;
    return CURLE_OK;
}

fn isPathSep(c: u8) bool {
    if (builtin.os.tag == .windows) {
        return c == '/' or c == '\\';
    } else {
        return c == '/';
    }
}

fn dirslash(path: [*:0]const u8) ?[*:0]u8 {
    const slice = std.mem.span(path);
    var n: usize = 0;
    if (builtin.os.tag == .windows) {
        const p1 = std.mem.lastIndexOfScalar(u8, slice, '/');
        const p2 = std.mem.lastIndexOfScalar(u8, slice, '\\');
        if (p1 != null and p2 != null) {
            n = @max(p1.?, p2.?);
        } else if (p1) |idx| {
            n = idx;
        } else if (p2) |idx| {
            n = idx;
        }
    } else {
        if (std.mem.lastIndexOfScalar(u8, slice, '/')) |idx| {
            n = idx;
        }
    }
    if (n > 0) {
        while (n > 0 and isPathSep(slice[n - 1])) {
            n -= 1;
        }
    }
    const pathsep: u8 = if (builtin.os.tag == .windows) '\\' else '/';
    const extra: usize = if (n > 0) 2 else 1;
    const out = mem.malloc(n + extra) orelse return null;
    if (n > 0) {
        @memcpy(out[0..n], slice[0..n]);
        out[n] = pathsep;
        out[n + 1] = 0;
    } else {
        out[0] = 0;
    }
    return @ptrCast(out);
}

const fopen_win32 = struct {
    const O_WRONLY: c_int = 0x0001;
    const O_CREAT: c_int = 0x0100;
    const O_EXCL: c_int = 0x0400;
    const S_IREAD: c_int = 0x0100;
    const S_IWRITE: c_int = 0x0080;

    extern fn _fdopen(fd: c_int, mode: [*:0]const u8) callconv(.c) ?*anyopaque;
    extern fn _close(fd: c_int) callconv(.c) c_int;
    extern fn _unlink(filename: [*:0]const u8) callconv(.c) c_int;
};

const fopen_posix = struct {
    extern fn fopen(filename: [*:0]const u8, mode: [*:0]const u8) callconv(.c) ?*anyopaque;
    extern fn fclose(stream: ?*anyopaque) callconv(.c) c_int;
    extern fn fileno(stream: ?*anyopaque) callconv(.c) c_int;
    extern fn fdopen(fd: c_int, mode: [*:0]const u8) callconv(.c) ?*anyopaque;
    extern fn close(fd: c_int) callconv(.c) c_int;
    extern fn unlink(filename: [*:0]const u8) callconv(.c) c_int;
    extern fn open(path: [*:0]const u8, oflag: c_int, ...) callconv(.c) c_int;
    extern fn fchmod(fd: c_int, mode: std.c.mode_t) callconv(.c) c_int;

    const FstatInfo = struct {
        mode: u32,
        uid: u32,
        gid: u32,
    };

    fn getFstat(fd: c_int, out: *FstatInfo) bool {
        if (builtin.os.tag == .linux) {
            var stx: std.os.linux.Statx = std.mem.zeroes(std.os.linux.Statx);
            const rc = std.os.linux.statx(
                fd,
                "",
                std.os.linux.AT.EMPTY_PATH,
                .{ .TYPE = true, .MODE = true, .UID = true, .GID = true },
                &stx,
            );
            if (std.os.linux.errno(rc) != .SUCCESS) return false;
            out.* = .{
                .mode = @intCast(stx.mode),
                .uid = @intCast(stx.uid),
                .gid = @intCast(stx.gid),
            };
            return true;
        } else {
            var st: std.c.Stat = std.mem.zeroes(std.c.Stat);
            if (std.c.fstat(fd, &st) == -1) return false;
            out.* = .{
                .mode = @intCast(st.mode),
                .uid = @intCast(st.uid),
                .gid = @intCast(st.gid),
            };
            return true;
        }
    }
};

fn buildTempstore(dir: [*:0]const u8, randbuf: [*:0]const u8) ?[*:0]u8 {
    const dir_slice = std.mem.span(dir);
    const rand_slice = std.mem.span(randbuf);
    const suffix = ".tmp";
    const total = dir_slice.len + rand_slice.len + suffix.len;
    const out = mem.malloc(total + 1) orelse return null;
    @memcpy(out[0..dir_slice.len], dir_slice);
    @memcpy(out[dir_slice.len .. dir_slice.len + rand_slice.len], rand_slice);
    @memcpy(out[dir_slice.len + rand_slice.len .. total], suffix);
    out[total] = 0;
    return @ptrCast(out);
}

pub export fn Curl_fopen(
    data: ?*anyopaque,
    filename: [*:0]const u8,
    fh: *?*anyopaque,
    tempname: *?[*:0]u8,
) callconv(.c) CURLcode {
    var result: CURLcode = CURLE_WRITE_ERROR;
    var randbuf: [41]u8 = undefined;
    var tempstore: ?[*:0]u8 = null;
    var fd: c_int = -1;

    tempname.* = null;

    if (builtin.os.tag == .windows) {
        fh.* = null;

        result = Curl_rand_alnum(data, &randbuf, randbuf.len);
        if (result != CURLE_OK) return result;

        if (dirslash(filename)) |dir| {
            tempstore = buildTempstore(dir, @ptrCast(&randbuf));
            mem.free(dir);
        }
        if (tempstore == null) return CURLE_OUT_OF_MEMORY;

        result = CURLE_WRITE_ERROR;
        fd = os_leaf.win32.curlx_win32_open(
            tempstore,
            fopen_win32.O_WRONLY | fopen_win32.O_CREAT | fopen_win32.O_EXCL,
            fopen_win32.S_IREAD | fopen_win32.S_IWRITE,
        );
        if (fd == -1) {
            mem.free(tempstore);
            return result;
        }
        fh.* = fopen_win32._fdopen(fd, "w");
        if (fh.* == null) {
            _ = fopen_win32._close(fd);
            _ = fopen_win32._unlink(tempstore.?);
            mem.free(tempstore);
            return result;
        }
        tempname.* = tempstore;
        return CURLE_OK;
    } else {
        fh.* = fopen_posix.fopen(filename, "w");
        if (fh.* == null) return CURLE_WRITE_ERROR;
        var sb: fopen_posix.FstatInfo = undefined;
        const fno = fopen_posix.fileno(fh.*);
        if (!fopen_posix.getFstat(fno, &sb) or (sb.mode & 0o170000) != 0o100000) {
            return CURLE_OK;
        }
        _ = fopen_posix.fclose(fh.*);
        fh.* = null;

        result = Curl_rand_alnum(data, &randbuf, randbuf.len);
        if (result != CURLE_OK) return result;

        if (dirslash(filename)) |dir| {
            tempstore = buildTempstore(dir, @ptrCast(&randbuf));
            mem.free(dir);
        }
        if (tempstore == null) return CURLE_OUT_OF_MEMORY;

        result = CURLE_WRITE_ERROR;
        const o_wronly: c_int = @bitCast(std.c.O{ .ACCMODE = .WRONLY });
        const o_creat: c_int = @bitCast(std.c.O{ .CREAT = true });
        const o_excl: c_int = @bitCast(std.c.O{ .EXCL = true });
        fd = fopen_posix.open(tempstore.?, o_wronly | o_creat | o_excl, @as(c_uint, 0o600));
        if (fd == -1) {
            mem.free(tempstore);
            return result;
        }

        var nsb: fopen_posix.FstatInfo = undefined;
        if (fopen_posix.getFstat(fd, &nsb) and nsb.uid == sb.uid and nsb.gid == sb.gid) {
            if (fopen_posix.fchmod(fd, @intCast(sb.mode)) == -1) {
                _ = fopen_posix.close(fd);
                _ = fopen_posix.unlink(tempstore.?);
                mem.free(tempstore);
                return result;
            }
        }

        fh.* = fopen_posix.fdopen(fd, "w");
        if (fh.* == null) {
            _ = fopen_posix.close(fd);
            _ = fopen_posix.unlink(tempstore.?);
            mem.free(tempstore);
            return result;
        }
        tempname.* = tempstore;
        return CURLE_OK;
    }
}

