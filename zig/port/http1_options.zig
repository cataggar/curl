test "Curl_rand_hex and Curl_rand_alnum" {
    var hex_buf: [33]u8 = undefined;
    @memset(&hex_buf, 0xFF);
    try std.testing.expectEqual(CURLE_OK, Curl_rand_hex(null, &hex_buf, hex_buf.len));
    try std.testing.expectEqual(@as(u8, 0), hex_buf[32]);
    for (hex_buf[0..32]) |ch| {
        const is_lower_hex = (ch >= '0' and ch <= '9') or (ch >= 'a' and ch <= 'f');
