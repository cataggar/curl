test "Curl_creds_create, merge, same, equal, and unlink" {
    var creds: ?*Curl_creds = null;
    defer Curl_creds_unlink(&creds);

    // All-null inputs produce NULL credential
    try std.testing.expectEqual(CURLE_OK, Curl_creds_create(null, null, null, null, null, CREDS_URL, &creds));
    try std.testing.expect(creds == null);

    // Non-null user/passwd
    try std.testing.expectEqual(CURLE_OK, Curl_creds_create("alice", "s3cr3t", null, null, null, CREDS_URL, &creds));
    try std.testing.expect(creds != null);
    try std.testing.expectEqualStrings("alice", std.mem.span(creds.?.user));
    try std.testing.expectEqualStrings("s3cr3t", std.mem.span(creds.?.passwd));
    try std.testing.expectEqual(CREDS_URL, creds.?.source);

    var merged: ?*Curl_creds = null;
    defer Curl_creds_unlink(&merged);
    try std.testing.expectEqual(CURLE_OK, Curl_creds_merge(null, "newpass", creds, CREDS_OPTION, &merged));
    try std.testing.expect(merged != null);
    try std.testing.expectEqualStrings("alice", std.mem.span(merged.?.user));
    try std.testing.expectEqualStrings("newpass", std.mem.span(merged.?.passwd));
    try std.testing.expect(!Curl_creds_same(creds, merged));

    var copy: ?*Curl_creds = null;
    defer Curl_creds_unlink(&copy);
    try std.testing.expectEqual(CURLE_OK, Curl_creds_merge(null, null, merged, CREDS_URL, &copy));
    try std.testing.expect(Curl_creds_same(merged, copy));
    try std.testing.expect(!Curl_creds_equal(merged, copy));
}

