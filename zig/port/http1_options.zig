test "curl_easy_option_by_name, curl_easy_option_by_id, and curl_easy_option_next" {
    try std.testing.expectEqual(@as(c_int, 0), Curl_easyopts_check());

    // Lookup by name (case-insensitive)
    const url_opt = curl_easy_option_by_name("URL");
    try std.testing.expect(url_opt != null);
    try std.testing.expectEqual(CURLOPT_URL, url_opt.?.id);
    try std.testing.expectEqual(CURLOT_STRING, url_opt.?.type);
    try std.testing.expectEqual(@as(c_uint, 0), url_opt.?.flags);

    const url_lower = curl_easy_option_by_name("url");
    try std.testing.expectEqual(url_opt, url_lower);

    // Alias lookup by name vs canonical lookup by ID
    const encoding_alias = curl_easy_option_by_name("ENCODING");
    try std.testing.expect(encoding_alias != null);
    try std.testing.expectEqual(CURLOPT_ACCEPT_ENCODING, encoding_alias.?.id);
    try std.testing.expectEqual(CURLOT_FLAG_ALIAS, encoding_alias.?.flags);

    const by_id = curl_easy_option_by_id(CURLOPT_ACCEPT_ENCODING);
    try std.testing.expect(by_id != null);
    try std.testing.expectEqualStrings("ACCEPT_ENCODING", std.mem.span(by_id.?.name.?));
    try std.testing.expectEqual(@as(c_uint, 0), by_id.?.flags);

    // Invalid lookups
    try std.testing.expect(curl_easy_option_by_name(null) == null);
    try std.testing.expect(curl_easy_option_by_name("NONEXISTENT_OPTION") == null);
    try std.testing.expect(curl_easy_option_by_id(0) == null);
    try std.testing.expect(curl_easy_option_by_id(CURLOPT_LASTENTRY) == null);

    // Iteration via curl_easy_option_next
    var count: usize = 0;
    var cur = curl_easy_option_next(null);
    while (cur) |o| : (cur = curl_easy_option_next(o)) {
        try std.testing.expect(o.name != null);
        count += 1;
    }
    try std.testing.expectEqual(Curl_easyopts.len - 1, count);
}

