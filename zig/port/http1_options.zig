pub export fn Curl_easyopts_check() callconv(.c) c_int {
    var i: usize = 0;
    while (Curl_easyopts[i].name != null) : (i += 1) {
        if (Curl_easyopts[i + 1].name) |next_name| {
            const cur_name = Curl_easyopts[i].name.?;
            if (std.mem.orderZ(u8, cur_name, next_name) != .lt) {
                return 1;
            }
        }
    }
    return 0;
}

fn lookup(name: ?[*:0]const u8, id: c_uint) ?*const curl_easyoption {
    var i: usize = 0;
    while (Curl_easyopts[i].name != null) : (i += 1) {
        const o = &Curl_easyopts[i];
        if (name) |n| {
            if (primitives.curl_strequal(o.name, n) != 0)
                return o;
        } else {
            if ((o.id == id) and (o.flags & CURLOT_FLAG_ALIAS) == 0)
                return o;
        }
    }
    return null;
}

pub export fn curl_easy_option_by_name(name: ?[*:0]const u8) callconv(.c) ?*const curl_easyoption {
    return lookup(name, CURLOPT_LASTENTRY);
}

pub export fn curl_easy_option_by_id(id: c_uint) callconv(.c) ?*const curl_easyoption {
    if (id != 0)
        return lookup(null, id);
    return null;
}

pub export fn curl_easy_option_next(prev: ?*const curl_easyoption) callconv(.c) ?*const curl_easyoption {
    if (prev) |p| {
        if (p.name != null) {
            const mp: [*]const curl_easyoption = @ptrCast(p);
            const next = &mp[1];
            if (next.name != null)
                return next;
        }
    } else {
        return &Curl_easyopts[0];
    }
    return null;
}

